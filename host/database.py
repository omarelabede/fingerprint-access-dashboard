"""SQLite persistence for validated access events and security alerts."""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from pathlib import Path
import sqlite3
from typing import Any

try:
    from .protocol import Event, ProtocolError, parse_event
except ImportError:  # Supports running sibling modules directly from host/.
    from protocol import Event, ProtocolError, parse_event


class ProcessResult(str, Enum):
    """Outcome of processing one incoming serial line."""

    STORED = "STORED"
    REPLAY_SUSPECTED = "REPLAY_SUSPECTED"
    INVALID_EVENT = "INVALID_EVENT"


def utc_now() -> str:
    """Return an ISO-8601 UTC timestamp generated by the host."""

    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


class EventDatabase:
    """Small SQLite repository used by the logger and read-only dashboard."""

    def __init__(self, database_path: str | Path = "access_control.db") -> None:
        self.database_path = str(database_path)
        self.connection = sqlite3.connect(self.database_path, timeout=10.0)
        self.connection.row_factory = sqlite3.Row
        self.connection.execute("PRAGMA busy_timeout = 10000")
        self.connection.execute("PRAGMA foreign_keys = ON")
        self.connection.execute("PRAGMA journal_mode = WAL")
        self.connection.execute("PRAGMA synchronous = NORMAL")
        self._closed = False
        self._create_schema()

    def _create_schema(self) -> None:
        with self.connection:
            self.connection.executescript(
                """
                CREATE TABLE IF NOT EXISTS access_events (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    device_id TEXT NOT NULL,
                    boot_id INTEGER NOT NULL,
                    event_seq INTEGER NOT NULL,
                    uptime_ms INTEGER NOT NULL,
                    event_type TEXT NOT NULL,
                    template_id INTEGER NOT NULL,
                    user_name TEXT NOT NULL,
                    confidence INTEGER NOT NULL,
                    authentication_result TEXT NOT NULL,
                    access_status TEXT NOT NULL,
                    reason TEXT NOT NULL,
                    failed_count INTEGER NOT NULL,
                    latency_ms INTEGER NOT NULL,
                    indicator_state TEXT NOT NULL,
                    received_at TEXT NOT NULL,
                    raw_line TEXT NOT NULL,
                    UNIQUE(device_id, boot_id, event_seq)
                );

                CREATE TABLE IF NOT EXISTS security_alerts (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    alert_type TEXT NOT NULL,
                    device_id TEXT,
                    boot_id INTEGER,
                    event_seq INTEGER,
                    raw_line TEXT NOT NULL,
                    description TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );

                CREATE INDEX IF NOT EXISTS idx_access_events_received_at
                    ON access_events(received_at DESC, id DESC);
                CREATE INDEX IF NOT EXISTS idx_security_alerts_created_at
                    ON security_alerts(created_at DESC, id DESC);
                """
            )
            self.connection.execute("PRAGMA optimize")

    def insert_event(self, event: Event) -> ProcessResult:
        """Insert a valid event, or create a replay alert for a duplicate key."""

        statement = """
            INSERT INTO access_events (
                device_id, boot_id, event_seq, uptime_ms, event_type,
                template_id, user_name, confidence, authentication_result,
                access_status, reason, failed_count, latency_ms,
                indicator_state, received_at, raw_line
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """
        values = (
            event.device_id,
            event.boot_id,
            event.event_seq,
            event.uptime_ms,
            event.event_type,
            event.template_id,
            event.user_name,
            event.confidence,
            event.authentication_result,
            event.access_status,
            event.reason,
            event.failed_count,
            event.latency_ms,
            event.indicator_state,
            utc_now(),
            event.raw_line,
        )

        try:
            with self.connection:
                self.connection.execute(statement, values)
        except sqlite3.IntegrityError:
            existing = self.connection.execute(
                """
                SELECT id FROM access_events
                WHERE device_id = ? AND boot_id = ? AND event_seq = ?
                """,
                (event.device_id, event.boot_id, event.event_seq),
            ).fetchone()
            if existing is None:
                raise
            self.add_alert(
                alert_type="REPLAY_SUSPECTED",
                raw_line=event.raw_line,
                description=(
                    "Duplicate event key received; the access event was not inserted "
                    f"(existing row {existing['id']})."
                ),
                device_id=event.device_id,
                boot_id=event.boot_id,
                event_seq=event.event_seq,
            )
            return ProcessResult.REPLAY_SUSPECTED

        return ProcessResult.STORED

    def add_alert(
        self,
        *,
        alert_type: str,
        raw_line: str,
        description: str,
        device_id: str | None = None,
        boot_id: int | None = None,
        event_seq: int | None = None,
    ) -> None:
        """Store a security alert using a host-generated UTC timestamp."""

        with self.connection:
            self.connection.execute(
                """
                INSERT INTO security_alerts (
                    alert_type, device_id, boot_id, event_seq,
                    raw_line, description, created_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    alert_type,
                    device_id,
                    boot_id,
                    event_seq,
                    raw_line.rstrip("\r\n"),
                    description,
                    utc_now(),
                ),
            )

    @staticmethod
    def _best_effort_identity(raw_line: str) -> tuple[str | None, int | None, int | None]:
        fields = raw_line.rstrip("\r\n").split("|")
        device_id = fields[1] if len(fields) > 1 and fields[1] else None

        def optional_integer(index: int) -> int | None:
            if len(fields) <= index:
                return None
            try:
                return int(fields[index])
            except ValueError:
                return None

        return device_id, optional_integer(2), optional_integer(3)

    def record_invalid_event(self, raw_line: str, description: str) -> None:
        """Record malformed input as INVALID_EVENT without creating an access row."""

        device_id, boot_id, event_seq = self._best_effort_identity(raw_line)
        self.add_alert(
            alert_type="INVALID_EVENT",
            raw_line=raw_line,
            description=description,
            device_id=device_id,
            boot_id=boot_id,
            event_seq=event_seq,
        )

    def process_line(self, raw_line: str) -> ProcessResult:
        """Validate and persist a line, converting failures into security alerts."""

        try:
            event = parse_event(raw_line)
        except ProtocolError as exc:
            self.record_invalid_event(raw_line, str(exc))
            return ProcessResult.INVALID_EVENT
        return self.insert_event(event)

    def summary(self) -> dict[str, int | bool]:
        """Return all dashboard counters in a single consistent snapshot."""

        row = self.connection.execute(
            """
            WITH
            event_counts AS (
                SELECT
                    COUNT(*) AS total_events,
                    COALESCE(SUM(CASE WHEN event_type = 'ACCESS' THEN 1 ELSE 0 END), 0)
                        AS total_attempts,
                    COALESCE(SUM(CASE WHEN event_type = 'ACCESS'
                                          AND authentication_result = 'SUCCESS'
                                      THEN 1 ELSE 0 END), 0) AS successful_attempts,
                    COALESCE(SUM(CASE WHEN event_type = 'ACCESS'
                                          AND authentication_result = 'FAILED'
                                      THEN 1 ELSE 0 END), 0) AS failed_attempts,
                    COALESCE(SUM(CASE WHEN event_type = 'ACCESS' AND template_id = 1
                                      THEN 1 ELSE 0 END), 0) AS administrator_attempts,
                    COALESCE(SUM(CASE WHEN event_type = 'ACCESS' AND template_id = 2
                                      THEN 1 ELSE 0 END), 0) AS technician_attempts,
                    COALESCE(SUM(CASE WHEN event_type = 'ACCESS'
                                          AND authentication_result = 'FAILED'
                                      THEN 1 ELSE 0 END), 0) AS unknown_attempts,
                    COALESCE(SUM(CASE WHEN event_type = 'LOCKOUT_START'
                                      THEN 1 ELSE 0 END), 0) AS lockout_events,
                    COALESCE(SUM(CASE WHEN event_type = 'SYSTEM_ERROR'
                                      THEN 1 ELSE 0 END), 0) AS system_errors,
                    COALESCE(ROUND(AVG(CASE WHEN event_type = 'ACCESS'
                                            THEN latency_ms END)), 0) AS average_latency
                FROM access_events
            ),
            alert_counts AS (
                SELECT
                    COUNT(*) AS total_alerts,
                    COALESCE(SUM(CASE WHEN alert_type = 'REPLAY_SUSPECTED'
                                      THEN 1 ELSE 0 END), 0) AS replay_suspected,
                    COALESCE(SUM(CASE WHEN alert_type = 'INVALID_EVENT'
                                      THEN 1 ELSE 0 END), 0) AS invalid_events
                FROM security_alerts
            ),
            latest_stream AS (
                SELECT device_id, boot_id
                FROM access_events
                ORDER BY id DESC
                LIMIT 1
            ),
            latest_lockout AS (
                SELECT event.event_type
                FROM access_events AS event
                JOIN latest_stream
                  ON latest_stream.device_id = event.device_id
                 AND latest_stream.boot_id = event.boot_id
                WHERE event.event_type IN ('LOCKOUT_START', 'LOCKOUT_END')
                ORDER BY event.id DESC
                LIMIT 1
            )
            SELECT
                event_counts.*,
                alert_counts.*,
                COALESCE(
                    (SELECT event_type = 'LOCKOUT_START' FROM latest_lockout),
                    0
                ) AS active_lockout
            FROM event_counts
            CROSS JOIN alert_counts
            """
        ).fetchone()

        result: dict[str, int | bool] = {key: int(row[key]) for key in row.keys()}
        result["active_lockout"] = bool(result["active_lockout"])
        return result

    def latest_access_event(self, template_id: int) -> dict[str, Any] | None:
        """Return the latest ACCESS row for one authorized template."""

        row = self.connection.execute(
            """
            SELECT id, device_id, boot_id, event_seq, uptime_ms, event_type,
                   template_id, user_name, confidence, authentication_result,
                   access_status, reason, failed_count, latency_ms,
                   indicator_state, received_at
            FROM access_events
            WHERE event_type = 'ACCESS' AND template_id = ?
            ORDER BY id DESC
            LIMIT 1
            """,
            (template_id,),
        ).fetchone()
        return dict(row) if row is not None else None

    def dashboard_snapshot(
        self, event_limit: int = 200, alert_limit: int = 100
    ) -> dict[str, Any]:
        """Read dashboard data atomically while the logger may keep writing."""

        self.connection.execute("BEGIN")
        try:
            snapshot = {
                "summary": self.summary(),
                "events": self.recent_events(event_limit),
                "alerts": self.recent_alerts(alert_limit),
                "latest_administrator": self.latest_access_event(1),
                "latest_technician": self.latest_access_event(2),
            }
            self.connection.commit()
            return snapshot
        except BaseException:
            self.connection.rollback()
            raise

    def recent_events(self, limit: int = 50) -> list[dict[str, Any]]:
        """Return the newest access events, bounded to a safe page size."""

        safe_limit = max(1, min(int(limit), 200))
        rows = self.connection.execute(
            """
            SELECT id, device_id, boot_id, event_seq, uptime_ms, event_type,
                   template_id, user_name, confidence, authentication_result,
                   access_status, reason, failed_count, latency_ms,
                   indicator_state, received_at
            FROM access_events
            ORDER BY id DESC
            LIMIT ?
            """,
            (safe_limit,),
        ).fetchall()
        return [dict(row) for row in rows]

    def recent_alerts(self, limit: int = 50) -> list[dict[str, Any]]:
        """Return the newest security alerts, bounded to a safe page size."""

        safe_limit = max(1, min(int(limit), 200))
        rows = self.connection.execute(
            """
            SELECT id, alert_type, device_id, boot_id, event_seq,
                   description, created_at
            FROM security_alerts
            ORDER BY id DESC
            LIMIT ?
            """,
            (safe_limit,),
        ).fetchall()
        return [dict(row) for row in rows]

    def close(self) -> None:
        """Close the SQLite connection; repeated calls are harmless."""

        if not self._closed:
            self.connection.close()
            self._closed = True

    def __enter__(self) -> "EventDatabase":
        return self

    def __exit__(self, exc_type: object, exc: object, traceback: object) -> None:
        self.close()
